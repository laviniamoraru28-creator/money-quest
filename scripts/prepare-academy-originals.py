#!/usr/bin/env python3
"""Build the supplied English Academy archive privately, without altering any source PDF.

Usage: python3 scripts/prepare-academy-originals.py --source-dir PATH --output-dir PATH
No translation is generated by this script. Full paid PDFs never belong in public/.
"""
import argparse
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'content/printables/academy-originals.json'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def prepare(source, output):
    source, output = Path(source).resolve(), Path(output).resolve()
    if output == ROOT or ROOT in output.parents:
        raise ValueError('Write the paid archive outside the public source repository')
    manifest = json.loads(MANIFEST.read_text())
    inputs = []
    for item in manifest['worksheets']:
        # Supplied filenames contain escaped underscores; canonical copies are also accepted.
        matches = list(source.glob('*' + item['level'].upper() + '*.pdf'))
        if len(matches) != 1:
            raise ValueError('Expected exactly one original PDF for ' + item['level'])
        data = matches[0].read_bytes()
        if len(data) != item['bytes'] or digest(data) != item['sha256']:
            raise ValueError('Original PDF differs from the supplied, verified edition: ' + item['level'])
        inputs.append((item['file'], data))
    readme = (ROOT / 'content/printables/academy-originals-readme.txt').read_bytes()
    # Validate every source before creating output. Refuse to replace an existing archive.
    output.mkdir(parents=True, exist_ok=True, mode=0o700)
    archive = output / manifest['archive']['file']
    with zipfile.ZipFile(archive, 'x', zipfile.ZIP_DEFLATED) as bundle:
        for name, data in inputs + [('READ-ME.txt', readme)]:
            entry = zipfile.ZipInfo(name, (2026, 11, 3, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            bundle.writestr(entry, data)
    actual = archive.read_bytes()
    if len(actual) != manifest['archive']['bytes'] or digest(actual) != manifest['archive']['sha256']:
        archive.unlink()
        raise ValueError('Archive does not match the verified product manifest')
    archive.chmod(0o600)
    return archive


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', required=True, type=Path)
    parser.add_argument('--output-dir', required=True, type=Path)
    args = parser.parse_args()
    result = prepare(args.source_dir, args.output_dir)
    print(json.dumps({'archive': str(result), 'language': 'en', 'translatedPdfLocales': 0, 'ready': False}))
