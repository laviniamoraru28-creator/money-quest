import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {learningLabs} from "../src/content/learning-labs";
import {labAgeVariants,labTaskAtLevel} from "../src/content/lab-age-variants";
import {laboratoryTranslationSource,draftTranslatedLaboratory,assertTranslationShape} from "../src/lib/i18n/content-translations";
import {ACTIVE_LOCALES} from "../src/i18n/config";
const manifest=JSON.parse(readFileSync("src/content/translations/laboratories.sources.json","utf8"));
assert.deepEqual(manifest.locales,["ro"]);
assert.equal(manifest.regionalTargets.ro,"ro-RO");
const translations=JSON.parse(readFileSync("src/content/translations/laboratories.ro.json","utf8"));
assert.deepEqual(Object.keys(translations).sort(),learningLabs.map(lab=>lab.slug).sort());
assert.deepEqual(Object.keys(manifest.sources).sort(),Object.keys(translations).sort());
const text=(value:unknown):string=>typeof value==="string"?value:Array.isArray(value)?value.map(text).join("\n"):value&&typeof value==="object"?Object.values(value).map(text).join("\n"):"";
const number=(value:string)=>Number(value.replace(",","."));
const figures=(value:unknown)=>(text(value).match(/\d+(?:[.,]\d+)?/g)||[]).map(number);
const sterling=(value:unknown)=>Array.from(text(value).matchAll(/£\s*(\d+(?:[.,]\d{1,2})?)|(\d+(?:[.,]\d{1,2})?)\s*£/g),match=>number(match[1]??match[2]!));
const pence=(value:unknown)=>Array.from(text(value).matchAll(/\b(\d+)\s*(?:p\b|de pence\b)/g),match=>Number(match[1]));
let strings=0,tasks=0;
for(const lab of learningLabs){
 const source=laboratoryTranslationSource(lab,labAgeVariants),copy=translations[lab.slug];
 strings+=assertTranslationShape(source,copy,lab.slug);
 const translated=draftTranslatedLaboratory(lab,labAgeVariants,copy,manifest.sources[lab.slug]);
 assert.equal(translated.lab.slug,lab.slug);
 assert.notEqual(translated.lab.title,lab.title);
 assert.notEqual(translated.lab.description,lab.description);
 assert.deepEqual(figures(copy),figures(source),`${lab.slug}: quantities and decimal values`);
 assert.deepEqual(sterling(copy),sterling(source),`${lab.slug}: sterling amounts, accepting Romanian decimal commas and symbol order`);
 assert.deepEqual(pence(copy),pence(source),`${lab.slug}: pence values`);
 const prose=text(copy);
 assert.equal(prose,prose.normalize("NFC"));assert(!/[\uFFFDŞşŢţ]/u.test(prose),"Valid Romanian diacritics, no replacement glyphs or legacy cedillas");
 assert(!/\s+[,.!?]/u.test(prose),"No spaces before Romanian sentence punctuation");
 assert(!/\b(?:remember|choose|trusted|situation|feedback|claim)\b/i.test(prose),"No obvious English prose left in this draft");
 lab.tasks.forEach((task,index)=>{
  tasks++;
  const result=translated.lab.tasks[index]!;
  assert.equal(result.id,task.id);assert.equal(result.correct,task.correct);
  assert.equal(result.tryIt.length,3);assert.equal(new Set(result.tryIt).size,3);
  const levels=[0,1,2].map(level=>labTaskAtLevel(lab.slug,result,level,translated.variants));
  assert.equal(new Set(levels.map(reading=>reading.idea)).size,3,`${task.id}: age-specific ideas`);
  assert.equal(new Set(levels.map(reading=>reading.situation)).size,3,`${task.id}: age-specific scenarios`);
  for(const reading of levels){assert.equal(reading.correct,task.correct);assert.equal(new Set(reading.choices).size,3);assert(reading.explanation.length>30);}
  assert.equal(levels[0]!.idea,copy.tasks[index].readings[0].idea);
  assert.equal(levels[1]!.idea,copy.tasks[index].idea);
  assert.equal(levels[2]!.idea,copy.tasks[index].readings[1].idea);
  assert.notEqual(levels[0]!.idea,labTaskAtLevel(lab.slug,task,0).idea,"Localized age selection must not use the global English readings");
  assert.equal(labTaskAtLevel(lab.slug,task,1),task,"Existing English Builder path remains unchanged");
 });
 assert.throws(()=>draftTranslatedLaboratory({...lab,description:lab.description+" changed"},labAgeVariants,copy,manifest.sources[lab.slug]));
 const sourceVariants=structuredClone(labAgeVariants);
 sourceVariants[`${lab.slug}:${lab.tasks[0]!.id}`]![1].explanation+=" changed";
 assert.throws(()=>draftTranslatedLaboratory(lab,sourceVariants,copy,manifest.sources[lab.slug]));
 const wrong=structuredClone(copy);wrong.tasks[0].correct=(wrong.tasks[0].correct+1)%3;
 assert.throws(()=>draftTranslatedLaboratory(lab,labAgeVariants,wrong,manifest.sources[lab.slug]));
 const missing=structuredClone(copy);missing.tasks[0].readings.pop();
 assert.throws(()=>draftTranslatedLaboratory(lab,labAgeVariants,missing,manifest.sources[lab.slug]));
 const extra=structuredClone(copy);extra.tasks[0].id="changed-id";
 assert.throws(()=>draftTranslatedLaboratory(lab,labAgeVariants,extra,manifest.sources[lab.slug]));
}
assert.equal(strings,490);assert.equal(tasks,22);
assert.deepEqual(ACTIVE_LOCALES,["en"],"Do not activate a partially translated website");
console.log(`PASS: three Romanian laboratory drafts, ${tasks} tasks, three age readings, ${strings} strings, localized age selection, correct answers, quantities and GBP/pence, with source/metadata/structure guards.`);
